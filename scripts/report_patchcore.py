"""Table of PatchCore results vs anomalib's published numbers (step-1 gate 3).

    uv run python scripts/report_patchcore.py --protocol official

Reads models/patchcore/<category>/<protocol>/metrics.json and
configs/vision/published/anomalib_patchcore_mvtec_ad.yaml; writes
reports/patchcore_mvtec_ad_<protocol>.md and prints it. Δ > 0.02 is flagged.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml

from iqs_vision.data.mvtec import CATEGORIES

ROOT = Path(__file__).resolve().parents[1]
TOLERANCE = 0.02


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--protocol", choices=["official", "deploy"], default="official")
    p.add_argument("--models-dir", type=Path, default=ROOT / "models/patchcore")
    p.add_argument(
        "--published",
        type=Path,
        default=ROOT / "configs/vision/published/anomalib_patchcore_mvtec_ad.yaml",
    )
    p.add_argument("--out", type=Path, default=None)
    args = p.parse_args(argv)
    pub = yaml.safe_load(args.published.read_text())
    rows, ours_i, ours_p, pub_i, pub_p = [], [], [], [], []
    for cat in CATEGORIES:
        f = args.models_dir / cat / args.protocol / "metrics.json"
        if not f.is_file():
            continue
        meta = json.loads(f.read_text())
        m = meta["metrics"]
        di = m["image_auroc"] - pub["image_auroc"][cat]
        dp = m["pixel_auroc"] - pub["pixel_auroc"][cat]
        flag = " ⚠" if max(abs(di), abs(dp)) > TOLERANCE else ""
        ours_i.append(m["image_auroc"])
        ours_p.append(m["pixel_auroc"])
        pub_i.append(pub["image_auroc"][cat])
        pub_p.append(pub["pixel_auroc"][cat])
        extra = ""
        if args.protocol == "deploy":
            extra = (
                f" | {m['threshold_max_calib']:.3f} | {m['test_false_alarm_rate']:.3f}"
                f" | {m['test_miss_rate']:.3f}"
            )
        rows.append(
            f"| {cat}{flag} | {m['image_auroc']:.3f} | {pub['image_auroc'][cat]:.3f} | {di:+.3f} "
            f"| {m['pixel_auroc']:.3f} | {pub['pixel_auroc'][cat]:.3f} | {dp:+.3f} "
            f"| {m.get('sup_test_image_auroc', float('nan')):.3f} "
            f"| {int(m['fit_images'])} | {m['seconds_fit'] / 60:.1f} "
            f"| {m['seconds_eval'] / 60:.1f} "
            f"| {m['peak_rss_mb'] / 1024:.1f}{extra} | `{(meta.get('mlflow_run_id') or '-')[:8]}` |"
        )
    if not rows:
        print("no results yet")
        return 1
    head = (
        "| Category | Image AUROC | Published | Δ | Pixel AUROC | Published | Δ "
        "| sup_test img AUROC | Fit imgs | Fit min | Eval min | Peak RSS GB"
    )
    sep = "| --- " * 12
    if args.protocol == "deploy":
        head += " | Thr (max calib) | Test FAR | Test miss"
        sep += "| --- " * 3
    head += " | MLflow run |"
    sep += "| --- |"
    n = len(rows)
    mean = (
        f"| **mean ({n})** | {sum(ours_i) / n:.3f} | {sum(pub_i) / n:.3f} "
        f"| {(sum(ours_i) - sum(pub_i)) / n:+.3f} | {sum(ours_p) / n:.3f} | {sum(pub_p) / n:.3f} "
        f"| {(sum(ours_p) - sum(pub_p)) / n:+.3f} |"
        + " |"
        * (6 + (3 if args.protocol == "deploy" else 0))
    )
    text = "\n".join(
        [
            f"# PatchCore on MVTec AD — protocol `{args.protocol}`",
            "",
            f"Published = {pub['source']} ({pub['backbone']}). ⚠ = |Δ| > {TOLERANCE}.",
            "Generated by `scripts/report_patchcore.py` from each model's metrics.json.",
            "",
            head,
            sep,
            *rows,
            mean,
            "",
        ]
    )
    out = args.out or ROOT / "reports" / f"patchcore_mvtec_ad_{args.protocol}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

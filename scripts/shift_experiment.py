"""Shift experiment (step 2 gate 4): the in-distribution conformal threshold under shift.

    uv run python scripts/shift_experiment.py --part real        # MVTec AD 2, saved scores
    uv run python scripts/shift_experiment.py --part synthetic   # MVTec AD, rescoring
    uv run python scripts/shift_experiment.py --part all

real:      for each calibrated MVTec AD 2 deploy model, false-alarm rate (with 95 % CI), miss
           rate and image AUROC per lighting condition, at the model's active threshold.
synthetic: MVTec AD deploy models whose active alpha is 0.02 (n >= 49); every good test image
           is rescored after each photometric transform in SYNTHETIC_SHIFTS.
Writes reports/shift_experiment.md and .json (the parts not run are kept from the last run).
Reported whatever the outcome: this is a measurement, not a target.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import numpy as np
import torch

from iqs_common.assets import load_assets, resolve_model_file
from iqs_vision.calibration.calibrate import CALIBRATION_FILE, SCORES_FILE, load_scores, select
from iqs_vision.calibration.shift import (
    SYNTHETIC_SHIFTS,
    all_conditions_auroc,
    condition_table,
    false_alarm_summary,
)
from iqs_vision.data import mvtec, mvtec_ad2
from iqs_vision.data.preprocess import image_to_tensor, load_image
from iqs_vision.data.splits import SplitManifest
from iqs_vision.detectors.patchcore import PatchCoreDetector

ROOT = Path(__file__).resolve().parents[1]


def _cal(model_dir: Path) -> dict[str, Any] | None:
    f = model_dir / CALIBRATION_FILE
    return json.loads(f.read_text()) if f.is_file() else None


def real_part(models: Path, protocol: str) -> list[dict[str, Any]]:
    out = []
    for cat in mvtec_ad2.CATEGORIES:
        d = models / cat / protocol
        cal = _cal(d)
        if cal is None or not (d / SCORES_FILE).is_file():
            continue
        _, records = load_scores(d / SCORES_FILE)
        out.append(
            {
                "category": cat,
                "alpha": cal["active"]["alpha"],
                "threshold": cal["threshold"],
                "all_conditions_image_auroc": all_conditions_auroc(records),
                "conditions": condition_table(records, cal["threshold"]),
            }
        )
    return out


def synthetic_part(models: Path, protocol: str, data_root: Path) -> list[dict[str, Any]]:
    assets = load_assets(ROOT / "configs/assets.yaml")
    out = []
    for cat in mvtec.CATEGORIES:
        d = models / cat / protocol
        cal = _cal(d)
        if cal is None or cal["active"]["alpha"] != 0.02:
            continue
        path = d / "model.pt"
        cfg_weights = PatchCoreDetector.read_config(path).weights
        weights = resolve_model_file(assets, cfg_weights, ROOT) if cfg_weights else None
        det, _ = PatchCoreDetector.load(path, weights)
        manifest = SplitManifest.load(ROOT / "eval_sets/vision/mvtec_ad" / f"{cat}.json")
        goods = [e for e in manifest.select("test") if e.label == 0]
        images = [load_image(data_root / e.path) for e in goods]
        _, records = load_scores(d / SCORES_FILE)
        base = select(records, "test", label=0)
        row: dict[str, Any] = {
            "category": cat,
            "alpha": 0.02,
            "threshold": cal["threshold"],
            "shifts": [{"shift": "none"} | false_alarm_summary(base, cal["threshold"])],
        }
        for name, transform in SYNTHETIC_SHIFTS.items():
            scores = []
            for i in range(0, len(images), det.cfg.batch_size):
                batch = torch.stack(
                    [
                        image_to_tensor(
                            transform(img), det.image_size, normalize=det.normalized_input
                        )
                        for img in images[i : i + det.cfg.batch_size]
                    ]
                )
                scores.append(det.predict(batch).scores)
            s = np.concatenate(scores)
            row["shifts"].append({"shift": name} | false_alarm_summary(s, cal["threshold"]))
        print(json.dumps({"category": cat, "done": True}), flush=True)
        out.append(row)
    return out


def _pct(x: float) -> str:
    return f"{100 * x:.1f} %"


def markdown(result: dict[str, Any]) -> str:
    lines = [
        "# Shift experiment — in-distribution conformal threshold under shift",
        "",
        "Generated by `scripts/shift_experiment.py`. FA = false-alarm rate of good images at the",
        "model's active conformal threshold q̂ (α from decision D1), with a 95 % Clopper–Pearson",
        "interval; median/q̂ = median good score divided by q̂ (> 1: most good parts flagged).",
        "Shifted images are not exchangeable with the calibration images, so no guarantee applies.",
        "",
    ]
    if result.get("real"):
        lines += ["## Real lighting conditions (MVTec AD 2 test_public)", ""]
        for r in result["real"]:
            lines += [
                f"### {r['category']} (α = {r['alpha']:.2f}, q̂ = {r['threshold']:.3f}; image AUROC "
                f"over all conditions {r['all_conditions_image_auroc']:.3f})",
                "",
                "| Condition | Good FA | FA 95 % CI | median/q̂ | Miss rate | Image AUROC |",
                "| --- | --- | --- | --- | --- | --- |",
            ]
            for c in r["conditions"]:
                ci = c.get("false_alarm_ci95", [float("nan")] * 2)
                lines.append(
                    f"| {c['condition']} | {c.get('false_alarms')}/{c.get('n_good')} = "
                    f"{_pct(c.get('false_alarm_rate', float('nan')))} "
                    f"| [{_pct(ci[0])}, {_pct(ci[1])}] "
                    f"| {c.get('median_good_score_over_threshold', float('nan')):.2f} "
                    f"| {_pct(c.get('miss_rate', float('nan')))} "
                    f"| {c.get('image_auroc', float('nan')):.3f} |"
                )
            lines.append("")
    if result.get("synthetic"):
        names = ["none", *SYNTHETIC_SHIFTS]
        lines += [
            "## Synthetic photometric shifts (MVTec AD good test images, α = 0.02 categories)",
            "",
            "| Category | " + " | ".join(names) + " |",
            "| --- | " + " | ".join("---" for _ in names) + " |",
        ]
        for r in result["synthetic"]:
            cells = {s["shift"]: s for s in r["shifts"]}
            lines.append(
                f"| {r['category']} | "
                + " | ".join(
                    f"{cells[n]['false_alarms']}/{cells[n]['n_good']} = "
                    f"{_pct(cells[n]['false_alarm_rate'])}"
                    for n in names
                )
                + " |"
            )
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("--part", choices=["real", "synthetic", "all"], default="all")
    p.add_argument("--protocol", default="deploy")
    p.add_argument("--models-dir", type=Path, default=ROOT / "models/patchcore")
    p.add_argument("--data-root", type=Path, default=ROOT / "data/raw/mvtec_ad")
    p.add_argument("--out-dir", type=Path, default=ROOT / "reports")
    args = p.parse_args(argv)
    out_json = args.out_dir / "shift_experiment.json"
    result: dict[str, Any] = json.loads(out_json.read_text()) if out_json.is_file() else {}
    if args.part in ("real", "all"):
        result["real"] = real_part(args.models_dir, args.protocol)
    if args.part in ("synthetic", "all"):
        result["synthetic"] = synthetic_part(args.models_dir, args.protocol, args.data_root)
    if not result.get("real") and not result.get("synthetic"):
        print("no calibrated models found", file=sys.stderr)
        return 2
    args.out_dir.mkdir(parents=True, exist_ok=True)
    out_json.write_text(json.dumps(result, indent=1) + "\n")
    md = markdown(result)
    (args.out_dir / "shift_experiment.md").write_text(md)
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())

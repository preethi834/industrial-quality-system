"""Alembic migrations, outbox constraints and pgvector against a real Postgres 16."""

from __future__ import annotations

import uuid
from datetime import UTC, datetime

import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from pgvector.sqlalchemy import Vector
from sqlalchemy import Column, Engine, Integer, MetaData, Table, inspect, select, text
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from iqs_common.db import Base
from iqs_common.events import NewDefectClusterEvent, NewDefectClusterPayload, parse_event
from iqs_common.outbox import OutboxEvent, OutboxStatus

pytestmark = pytest.mark.integration

SCHEMAS = {"diagnosis", "vision", "qms", "platform"}


def _schemas(engine: Engine) -> set[str]:
    return set(inspect(engine).get_schema_names())


def _extensions(engine: Engine) -> set[str]:
    with engine.connect() as conn:
        return set(conn.execute(text("SELECT extname FROM pg_extension")).scalars())


def _event() -> NewDefectClusterEvent:
    now = datetime(2026, 11, 17, 12, 0, tzinfo=UTC)
    return NewDefectClusterEvent(
        payload=NewDefectClusterPayload(
            cluster_id=uuid.uuid4(),
            category="bottle",
            size=2,
            first_seen=now,
            last_seen=now,
            inspection_ids=(uuid.uuid4(),),
            model_version="patchcore-v1",
        )
    )


def test_upgrade_creates_extension_schemas_and_outbox(migrated: Config, pg_engine: Engine) -> None:
    assert "vector" in _extensions(pg_engine)
    assert "pg_trgm" not in _extensions(pg_engine)
    assert SCHEMAS <= _schemas(pg_engine)
    insp = inspect(pg_engine)
    assert insp.get_table_names(schema="platform") == ["events"]
    checks = {c["name"] for c in insp.get_check_constraints("events", schema="platform")}
    assert checks == {"ck_events_status", "ck_events_attempts_non_negative"}
    # alembic_version lives in public; no other public tables.
    assert insp.get_table_names(schema="public") == ["alembic_version"]
    with pg_engine.connect() as conn:
        head = ScriptDirectory.from_config(migrated).get_current_head()
        assert conn.execute(text("SELECT version_num FROM alembic_version")).scalar() == head


def test_downgrade_to_base_removes_everything_then_upgrade_again(
    alembic_cfg: Config, pg_engine: Engine
) -> None:
    command.upgrade(alembic_cfg, "head")
    command.downgrade(alembic_cfg, "base")
    assert not (SCHEMAS & _schemas(pg_engine))
    assert "vector" not in _extensions(pg_engine)
    command.upgrade(alembic_cfg, "head")
    assert SCHEMAS <= _schemas(pg_engine)
    command.downgrade(alembic_cfg, "base")


def test_models_and_migrations_have_no_drift(migrated: Config) -> None:
    command.check(migrated)  # raises AutogenerateDiffsDetected on any difference


def test_drift_check_is_not_vacuous(migrated: Config) -> None:
    """A model table without a migration must be reported."""
    extra = Table(
        "drift_probe", Base.metadata, Column("id", Integer, primary_key=True), schema="platform"
    )
    try:
        with pytest.raises(AutogenerateDiffsDetected, match="drift_probe"):
            command.check(migrated)
    finally:
        Base.metadata.remove(extra)


def test_drift_check_ignores_objects_outside_our_schemas(
    migrated: Config, pg_engine: Engine
) -> None:
    with pg_engine.begin() as conn:
        conn.execute(text("CREATE TABLE public.not_ours (id int)"))
    try:
        command.check(migrated)
    finally:
        with pg_engine.begin() as conn:
            conn.execute(text("DROP TABLE public.not_ours"))


def test_outbox_round_trip_with_server_defaults(migrated: Config, pg_engine: Engine) -> None:
    event = _event()
    with Session(pg_engine) as session, session.begin():
        session.add(OutboxEvent.from_event(event))
    with Session(pg_engine) as session:
        row = session.scalars(select(OutboxEvent)).one()
        assert row.id == event.event_id
        assert row.status == OutboxStatus.PENDING
        assert row.attempts == 0
        assert row.created_at.tzinfo is not None
        assert row.processed_at is None
        assert parse_event(row.payload) == event


def test_server_defaults_apply_to_raw_inserts(migrated: Config, pg_engine: Engine) -> None:
    with pg_engine.begin() as conn:
        conn.execute(
            text("INSERT INTO platform.events (id, type, payload) VALUES (:id, 't', '{}')"),
            {"id": uuid.uuid4()},
        )
        status, attempts = conn.execute(text("SELECT status, attempts FROM platform.events")).one()
    assert (status, attempts) == ("pending", 0)


def test_duplicate_event_id_is_rejected(migrated: Config, pg_engine: Engine) -> None:
    event = _event()
    with Session(pg_engine) as session, session.begin():
        session.add(OutboxEvent.from_event(event))
    with pytest.raises(IntegrityError, match="pk_events"), Session(pg_engine) as session:
        with session.begin():
            session.add(OutboxEvent.from_event(event))


@pytest.mark.parametrize(
    ("column", "value", "constraint"),
    [
        ("status", "'bogus'", "ck_events_status"),
        ("attempts", "-1", "ck_events_attempts_non_negative"),
    ],
)
def test_check_constraints_reject_bad_values(
    migrated: Config, pg_engine: Engine, column: str, value: str, constraint: str
) -> None:
    sql = (
        f"INSERT INTO platform.events (id, type, payload, {column}) "
        f"VALUES (:id, 't', '{{}}', {value})"
    )
    with pytest.raises(IntegrityError, match=constraint), pg_engine.begin() as conn:
        conn.execute(text(sql), {"id": uuid.uuid4()})


def test_vector_round_trip(migrated: Config, pg_engine: Engine) -> None:
    probe = Table(
        "vector_probe",
        MetaData(),
        Column("id", Integer, primary_key=True),
        Column("embedding", Vector(3)),
        schema="platform",
    )
    with pg_engine.begin() as conn:
        probe.create(conn)
        try:
            conn.execute(
                probe.insert(),
                [{"id": 1, "embedding": [1.0, 2.0, 3.0]}, {"id": 2, "embedding": [1.0, 2.0, 4.0]}],
            )
            nearest = (
                conn.execute(
                    select(probe.c.id).order_by(probe.c.embedding.l2_distance([1.0, 2.0, 3.1]))
                )
                .scalars()
                .first()
            )
            stored = conn.execute(select(probe.c.embedding).where(probe.c.id == 1)).scalar_one()
        finally:
            probe.drop(conn)
    assert nearest == 1
    assert list(stored) == [1.0, 2.0, 3.0]
